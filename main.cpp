#include <string>
#include <vector>

void least_multiple() {
    int a = 6, b = 8;
    int x = a, y = b;
    while (y != 0) {
        int t = x % y;
        x = y;
        y = t;
    }
    int lcm = a / x * b;
    (void)lcm;
}

void center_digit() {
    int n = 98765;
    int digits = 0;
    int temp = n;
    while (temp > 0) { digits += 1; temp /= 10; }
    for (int i = 1; i < digits / 2; ++i) n /= 10;
    int center = n % 10;
    (void)center;
}

void count_multiples() {
    int count = 0;
    for (int i = 1; i <= 100; ++i) {
        if (i % 7 == 0) count += 1;
    }
    (void)count;
}

void sum_pair() {
    int left = 3;
    int right = 9;
    int total = left + right;
    (void)total;
}

